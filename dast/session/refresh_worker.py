"""
Session Refresh Worker — detects auth expiry and transparently re-authenticates.

Watches the proxy entry stream for session-expiry signals:
  - HTTP 401 or 403 responses on in-scope endpoints
  - HTTP 302 redirect to a URL containing 'login', 'signin', or 'auth'
  - Response body containing typical "session expired" phrases

Entries generated by the scanners themselves are NOT signals — the agents
(``x-dast-source: agent``) and the copilot probes (`source="copilot"`, which runs
its own relogin ladder) provoke 401/403s on purpose, and any entry carrying a
``probe_payload`` is an injected probe by definition. Only the operator's /
browser's real traffic counts.

When a signal is detected the worker:
  1. Waits for the cooldown window (avoids thundering herd on concurrent 401s) —
     signals arriving DURING the cooldown are coalesced into one deferred re-check
     instead of being dropped
  2. Runs the profile flow replay (or AuthAgent.login()) against the saved credentials
  3. Applies the refreshed auth state to the ContextPool AND syncs it into the
     shared proxy jar (so copilot send_request and the scan pool see the same session)
  4. Logs the outcome to the proxy event log

The breaker (``_gave_up``) is RECOVERABLE: ``reset()`` clears it — wired to
``POST /api/session/reauth/reset`` and to profile activations that land a verified
session — instead of the old give-up-forever behavior that only a process restart
cleared.

Only active when --auth-url and credentials were provided at startup.
Completely passive from the entry pipeline's perspective — no entries are
modified or re-queued.
"""

from __future__ import annotations

import asyncio
import re
import time
from typing import TYPE_CHECKING, Any, Optional

from dast.proxy.plugin_manager import log_event
from dast.utils.logger import get_logger

if TYPE_CHECKING:
    from dast.browser.context_pool import ContextPool
    from dast.proxy.session_store import ProxyEntry
    from dast.session.manager import SessionManager

logger = get_logger(__name__)

# Minimum gap between two re-auth attempts (seconds)
_REAUTH_COOLDOWN = 30.0

# Consecutive re-auth failures before the breaker trips. Re-authenticating with
# stale credentials (password changed, new MFA, login host down) will fail every
# time; without this the worker burns a browser context on every subsequent 401.
_MAX_REAUTH_FAILURES = 3

# Response body phrases that strongly suggest the session expired
_EXPIRY_PHRASES_RE = re.compile(
    r"(session\s+expired|your\s+session\s+has|you\s+have\s+been\s+logged\s+out"
    r"|please\s+log\s+in\s+again|authentication\s+required|unauthorized)",
    re.IGNORECASE,
)

# Location header patterns that indicate a redirect to the login page
_LOGIN_REDIRECT_RE = re.compile(
    r"/(login|signin|sign-in|sign_in|auth/login|account/login|users/sign_in)",
    re.IGNORECASE,
)

# Sources whose 401/403s are the SCANNER's own doing, not session expiry:
# "agent" = active-check/agent probes; "copilot" = the copilot's send_request/tools,
# which run their own relogin ladder (a second trigger here double-logins the same
# account). Any entry with a probe_payload is an injected probe regardless of source.
_SCANNER_SOURCES = ("agent", "copilot")

# Sentinel queued by the coalescing timer: "at least one signal arrived during the
# cooldown — run one more re-check when this is dequeued."
_COALESCED = object()


def _is_expiry_signal(entry: "ProxyEntry") -> bool:
    """Return True if the entry carries a session-expiry signal."""
    if entry.source in _SCANNER_SOURCES:
        return False
    if entry.probe_payload:
        # An injected probe (x-dast-payload) — its 401/403 is the probe's answer,
        # not a session dying under the operator's traffic.
        return False
    status = entry.response_status or 0

    # Explicit auth failure
    if status in (401, 403):
        return True

    # Redirect to login page
    if status in (301, 302, 303, 307, 308):
        location = entry.response_headers.get("location", "")
        if _LOGIN_REDIRECT_RE.search(location):
            return True

    # 200 response body that says "session expired"
    if status == 200 and entry.response_body:
        snippet = entry.response_body[:2048].decode("utf-8", errors="replace")
        if _EXPIRY_PHRASES_RE.search(snippet):
            return True

    return False


class SessionRefreshWorker:
    """
    Background worker that re-authenticates when session expiry is detected.

    Wire up by calling `attach(store)` then `run()` as a coroutine in
    asyncio.gather alongside the proxy.
    """

    def __init__(
        self,
        auth_url: str,
        username: str,
        password: Optional[str],
        pool: "ContextPool",
        session_manager: "SessionManager",
        proxy_port: Optional[int] = None,
        store: Optional[Any] = None,
    ) -> None:
        self._auth_url = auth_url
        self._username = username
        self._password = password
        self._pool = pool
        self._session_manager = session_manager
        self._proxy_port = proxy_port
        self._store = store
        self._signal_queue: asyncio.Queue = asyncio.Queue()
        self._last_reauth: float = 0.0
        self._consecutive_failures: int = 0
        self._gave_up: bool = False
        self._pending_signal: bool = False
        self._last_success_ts: float = 0.0  # wall-clock, for the dashboard
        self._last_failure_reason: str = ""

    # ── wiring ─────────────────────────────────────────────────────────────

    def on_entry(self, entry: "ProxyEntry") -> None:
        """Called by the proxy store after each entry completes. Non-blocking."""
        if _is_expiry_signal(entry):
            try:
                self._signal_queue.put_nowait(entry)
            except asyncio.QueueFull:
                pass  # already queued — cooldown will handle it

    # ── breaker control / observability ────────────────────────────────────

    def reset(self, reason: str = "manual reset") -> None:
        """Recover the breaker. The old `_gave_up` could only be cleared by a process
        restart; now a manual re-auth (Browse tab) or a profile activation that lands a
        VERIFIED session clears it via the dashboard route."""
        self._gave_up = False
        self._consecutive_failures = 0
        self._pending_signal = False
        log_event("session_refresh", "info",
                  f"Re-auth breaker reset ({reason}) — automatic re-auth re-armed",
                  source="plugin")
        logger.info("Session refresh: breaker reset", reason=reason)

    def state_snapshot(self) -> dict:
        """Dashboard-facing breaker state (GET /api/session/state)."""
        now = time.monotonic()
        cooldown_remaining = 0.0
        if self._last_reauth > 0:
            cooldown_remaining = max(0.0, _REAUTH_COOLDOWN - (now - self._last_reauth))
        return {
            "active": True,
            "gave_up": self._gave_up,
            "consecutive_failures": self._consecutive_failures,
            "max_failures": _MAX_REAUTH_FAILURES,
            "cooldown_active": cooldown_remaining > 0,
            "cooldown_remaining_s": round(cooldown_remaining, 1),
            "pending_signal": self._pending_signal,
            "last_success_ts": self._last_success_ts,
            "last_failure_reason": self._last_failure_reason,
            "auth_url": self._auth_url,
            "username": self._username,
        }

    # ── main loop ──────────────────────────────────────────────────────────

    async def run(self) -> None:
        """Long-running coroutine — run alongside the proxy in asyncio.gather."""
        logger.info(
            "SessionRefreshWorker started",
            auth_url=self._auth_url,
            username=self._username,
        )
        while True:
            item = await self._signal_queue.get()
            now = time.monotonic()

            # Circuit breaker: after too many consecutive failures, stop trying —
            # the credentials are clearly stale and every attempt wastes a browser
            # context. Recovery: SessionRefreshWorker.reset() (dashboard route or a
            # verified profile activation).
            if self._gave_up:
                logger.debug("Session refresh suppressed — breaker tripped; reset via "
                             "POST /api/session/reauth/reset or a profile activation")
                continue

            if item is _COALESCED:
                # Deferred re-check from the coalescing timer; drop if nothing
                # actually arrived meanwhile.
                if not self._pending_signal:
                    continue
                self._pending_signal = False
            else:
                if now - self._last_reauth < _REAUTH_COOLDOWN:
                    # COALESCE, don't drop: one deferred re-check will run after the
                    # cooldown so a signal that arrived mid-attempt is not lost.
                    if not self._pending_signal:
                        self._pending_signal = True
                        self._schedule_coalesced_run()
                    continue

            await self._reauth()
            # Cooldown measured from the END of the attempt: a slow browser login
            # must not eat its own recovery window (the old code stamped the
            # timestamp BEFORE the attempt).
            self._last_reauth = time.monotonic()

    def _schedule_coalesced_run(self) -> None:
        """After the cooldown, wake the loop once to serve coalesced signals."""
        try:
            loop = asyncio.get_running_loop()
            loop.call_later(_REAUTH_COOLDOWN + 0.5, self._fire_coalesced)
        except RuntimeError:
            pass  # no running loop (unit-test context) — nothing to schedule

    def _fire_coalesced(self) -> None:
        if self._pending_signal and not self._gave_up:
            # Keep `_pending_signal` set — the run loop's _COALESCED branch consumes
            # it; clearing here would make the loop drop the deferred re-check.
            try:
                self._signal_queue.put_nowait(_COALESCED)  # type: ignore[arg-type]
            except asyncio.QueueFull:
                pass

    # ── re-auth strategies ─────────────────────────────────────────────────

    async def _reauth(self) -> None:
        from dast.session.auth_agent import AuthAgent
        from dast.session.login_coordinator import get_login_coordinator

        # The shared login lock: a copilot/tool/dashboard login for the same host
        # must not run concurrently with this one (two logins with the same creds
        # can invalidate each other's server-side session).
        coord = get_login_coordinator()
        async with coord.lock_for(coord.site_key_for(self._auth_url)):
            await self._reauth_locked(AuthAgent)

    async def _reauth_locked(self, auth_agent_cls) -> None:
        # Prefer an encrypted login profile (recorded flow → saved session) when one
        # matches the auth host; only fall back to the single-form AuthAgent heuristic.
        if await self._try_profile_reauth():
            return

        try:
            async with self._pool.acquire() as ctx:
                agent = auth_agent_cls(
                    context=ctx,
                    session_manager=self._session_manager,
                    auth_url=self._auth_url,
                    username=self._username,
                    password=self._password,
                )
                ok = await agent.login()
                if ok:
                    state = await ctx.storage_state()
                    await self._apply_auth_state(state)
                    self._register_success()
                    log_event(
                        "session_refresh", "info",
                        "Re-authentication successful — auth state refreshed",
                        source="plugin",
                    )
                    logger.info("Session refresh: re-auth succeeded")
                else:
                    self._register_failure(
                        "Re-authentication failed — scan will continue unauthenticated"
                    )
        except Exception as exc:
            logger.error("Session refresh: unexpected error during re-auth", error=str(exc))
            self._register_failure(f"Re-auth error: {exc}")

    async def _try_profile_reauth(self) -> bool:
        """Try re-auth via a matching login profile. Returns True on success."""
        if not self._proxy_port:
            return False
        try:
            from urllib.parse import urlparse
            from dast.session.profile_reauth import reauth_from_profile

            host = urlparse(self._auth_url).hostname or ""
            state = await reauth_from_profile(host, self._proxy_port)
            if not state:
                return False
            await self._apply_auth_state(state)
            self._register_success()
            log_event(
                "session_refresh", "info",
                "Re-authentication successful via login profile — auth state refreshed",
                source="plugin",
            )
            logger.info("Session refresh: profile re-auth succeeded", host=host)
            return True
        except Exception as exc:
            logger.warning("Session refresh: profile re-auth error", error=str(exc))
            return False

    async def _apply_auth_state(self, state: dict) -> None:
        """Apply the fresh session to the pool contexts AND the shared proxy jar.

        The pool alone is not enough: copilot send_request and the tools read the
        STORE's jar (the startup login at runner.py seeds both for exactly this
        reason) — a re-auth that skipped the jar left the copilot 401ing with a
        perfectly fresh pool."""
        await self._pool.apply_auth_state(state)
        if self._store is not None and state.get("cookies"):
            try:
                imported = self._store.import_playwright_cookies(state["cookies"])
                logger.info("Session refresh: jar synced from fresh session",
                            cookies=imported)
            except Exception as exc:  # noqa: BLE001 — jar sync is best-effort
                logger.warning("Session refresh: jar sync failed", error=str(exc)[:120])

    # ── outcome bookkeeping ────────────────────────────────────────────────

    def _register_success(self) -> None:
        self._consecutive_failures = 0
        self._last_success_ts = time.time()
        self._last_failure_reason = ""

    def _register_failure(self, message: str) -> None:
        """Record a re-auth failure and trip the breaker at the threshold."""
        self._consecutive_failures += 1
        self._last_failure_reason = message
        logger.warning("Session refresh: re-auth failed",
                       consecutive_failures=self._consecutive_failures)
        if self._consecutive_failures >= _MAX_REAUTH_FAILURES:
            self._gave_up = True
            log_event(
                "session_refresh", "error",
                f"Re-authentication failed {self._consecutive_failures} times — automatic "
                "re-auth paused. Credentials may be stale (password/MFA changed). "
                "Re-authenticate via the Browse tab or a profile activation; the breaker "
                "resets automatically when a verified session lands, or immediately via "
                "POST /api/session/reauth/reset.",
                source="plugin",
            )
            logger.error("Session refresh: giving up after repeated failures",
                         failures=self._consecutive_failures)
        else:
            log_event("session_refresh", "error", message, source="plugin")
